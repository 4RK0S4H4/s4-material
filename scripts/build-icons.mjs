#!/usr/bin/env node
/* Build components/assets/icons.js from the icon vocabulary (components/icons/names.json) and the active set.
   Output: window.S4_ICONS = { set, viewBox, credit, icons: { semanticName: svgBody } }.
   Apps can also register more at run time with S4.icon.add({ name: body }).
   Usage: node scripts/build-icons.mjs [--check] */
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const cfg = JSON.parse(readFileSync(join(root, 'components/icons/names.json'), 'utf8'));
const set = cfg.sets[cfg.set];
const source = JSON.parse(readFileSync(join(root, set.source), 'utf8'));
const icons = {}, missing = [];
for (const [name, id] of Object.entries(cfg.names)) source[id] ? (icons[name] = source[id]) : missing.push(`${name} -> ${id}`);
if (missing.length) { console.error('Missing icons:\n  ' + missing.join('\n  ')); process.exit(1); }
const out = `/* S4 Orion icons. GENERATED by scripts/build-icons.mjs from components/icons/names.json. Do not edit.
   Icons: ${cfg.set} (${set.license}). Credit "Solar icons by 480 Design" on published pages. */
window.S4_ICONS = ${JSON.stringify({ set: cfg.set, viewBox: set.viewBox, credit: 'Solar icons by 480 Design (CC BY 4.0)', icons })};
`;
const file = join(root, 'components/assets/icons.js');
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== out) { console.error('Stale components/assets/icons.js (run npm run build:icons)'); process.exit(1); }
  console.log(`Icons up to date: ${Object.keys(icons).length}`);
} else { writeFileSync(file, out); console.log(`Built ${Object.keys(icons).length} icons -> components/assets/icons.js (${(out.length / 1024).toFixed(0)} KB)`); }

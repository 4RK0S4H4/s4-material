#!/usr/bin/env node
/* Bundle S4 Orion for apps and for the skill.
   - components/orion.css: tokens + base + every component + glass + motion, in the @import order of components/index.css,
     with url()s rewritten for the new location.
   - components/orion.js:  core, motion, then every component's script (same order).
   - skill/s4-orion/assets/: orion.css, orion.js, icons.js, m3color.js, inter-variable.woff2 (the skill ships its own copy).
   Run after npm run build:tokens and build:icons (npm run build does all three). --check fails if any output is stale.
   No dependencies. */
import { readFileSync, writeFileSync, existsSync, mkdirSync, copyFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, relative, posix } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const CHECK = process.argv.includes('--check');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const comp = join(root, 'components');
const entry = readFileSync(join(comp, 'index.css'), 'utf8');
const imports = [...entry.matchAll(/@import url\("([^"]+)"\)/g)].map((m) => m[1]);
const problems = [];

/* ---------- CSS ---------- */
function inlineCss(outDir, fontDir) {
  const parts = [];
  for (const rel of imports) {
    const file = join(comp, rel);
    if (!existsSync(file)) { problems.push(`missing ${relative(root, file)}`); continue; }
    let css = readFileSync(file, 'utf8');
    css = css.replace(/url\("?(?!data:|https?:|#)([^")]+)"?\)/g, (m, u) => {
      const abs = join(dirname(file), u);
      if (fontDir && /\.woff2$/.test(u)) return `url("${posix.join(fontDir, u.split('/').pop())}")`;
      return `url("${relative(outDir, abs).split('\\').join('/')}")`;
    });
    parts.push(`/* ---- ${relative(comp, file)} ---- */\n${css.trim()}\n`);
  }
  return parts;
}
const banner = (what) => `/* S4 Orion ${pkg.version} ${what}. GENERATED by scripts/build.mjs. Do not edit: change tokens/src or components/ and rebuild.
   Inter (SIL OFL 1.1) · Solar icons by 480 Design (CC BY 4.0) · Material Color Utilities (Apache 2.0) */\n`;
const cssRepo = banner('stylesheet') + inlineCss(comp).join('\n');
const cssSkill = banner('stylesheet') + inlineCss(comp, '.').join('\n');

/* ---------- JS ---------- */
const jsOrder = ['core/core.js', 'motion/motion.js'];
for (const rel of imports) {
  const dir = rel.split('/')[0];
  const js = `${dir}/${dir}.js`;
  if (existsSync(join(comp, js)) && !jsOrder.includes(js)) jsOrder.push(js);
}
const js = banner('runtime') + jsOrder.map((f) => `/* ---- ${f} ---- */\n${readFileSync(join(comp, f), 'utf8').trim()}\n`).join('\n');

/* ---------- write ---------- */
const skillAssets = join(root, 'skill/s4-orion/assets');
const outputs = {
  'components/orion.css': cssRepo,
  'components/orion.js': js,
  'skill/s4-orion/assets/orion.css': cssSkill,
  'skill/s4-orion/assets/orion.js': js,
};
const copies = {
  'skill/s4-orion/assets/icons.js': 'components/assets/icons.js',
  'skill/s4-orion/assets/m3color.js': 'components/assets/m3color.js',
  'skill/s4-orion/assets/inter-variable.woff2': 'components/assets/inter-variable.woff2',
};
/* ---------- skill references (generated, so they can't drift from the repo) ---------- */
const refs = {};
const GROUPS = [
  ['Actions', ['button', 'icon-button', 'button-group', 'fab']],
  ['Navigation and shell', ['app', 'top-app-bar', 'nav-bar', 'nav-rail', 'tabs', 'toolbar', 'search']],
  ['Containment and data', ['card', 'pane', 'list', 'table', 'divider']],
  ['Inputs', ['text-field', 'chip', 'switch', 'checkbox', 'radio', 'slider', 'swatches']],
  ['Feedback', ['badge', 'status', 'progress', 'snackbar', 'tooltip']],
  ['Overlays', ['menu', 'dialog', 'sheet']],
];
{
  const toc = [], body = [];
  for (const [g, names] of GROUPS) {
    toc.push(`- **${g}:** ` + names.map((n) => `[${n}](#${n})`).join(', '));
    for (const n of names) {
      const f = join(comp, n, 'README.md');
      if (!existsSync(f)) { problems.push(`missing components/${n}/README.md`); continue; }
      const md = readFileSync(f, 'utf8').replace(/^# (.+)$/m, `## $1 {#${n}}`).replace(/^## (?!.*\{#)/gm, '### ').replace(/\]\(\.\.\/([a-z-]+)\/\)/g, '](#$1)');
      body.push(`<a id="${n}"></a>\n\n` + md.replace(/ \{#[a-z-]+\}/, '').trim());
    }
  }
  refs['components.md'] = `# S4 Orion components\n\nGENERATED by scripts/build.mjs from components/*/README.md. Markup, attributes, when to use what, do/don't, accessibility.\nEvery component has a live reference page at https://4rk0s4h4.github.io/s4-material/components/<name>/<name>.html.\n\n## Contents\n\n${toc.join('\n')}\n\n` + body.join('\n\n---\n\n') + '\n';
}
{
  const T = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8')).tokens;
  const groups = [
    ['Color roles', /^--md-sys-color-/], ['Type scale', /^--md-sys-typescale-/], ['Typefaces', /^--md-ref-typeface-/],
    ['Shape scale', /^--md-sys-shape-corner-/], ['Component shapes', /^--s4-shape-/], ['Spacing', /^--s4-space-/], ['Sizes', /^--s4-size-/],
    ['Layout', /^--s4-layout-/], ['Breakpoints', /^--s4-breakpoint-/], ['Stacking (z-index)', /^--s4-z-/], ['Elevation', /^--md-sys-elevation-/],
    ['State', /^--md-sys-state-/], ['Focus and scrim', /^--s4-(focus|scrim)-/], ['Motion: springs', /^--(md-sys|s4)-motion-spring-/],
    ['Motion: patterns', /^--s4-motion-pattern-/], ['Glass', /^--s4-glass-/], ['Icons', /^--s4-icon-/]];
  const short = (v) => (v.startsWith('linear(') ? 'linear(…) spring easing' : v);
  const out = ['# S4 Orion tokens', '', 'GENERATED by scripts/build.mjs from tokens/tokens.json (source: tokens/src/*.tokens.json). Use these names; never write the values.',
    'Light values are shown; a second value is dark mode. Color roles also change with the seed at run time. Live: https://4rk0s4h4.github.io/s4-material/tokens/', ''];
  for (const [g, re] of groups) {
    const names = Object.keys(T).filter((n) => re.test(n) && !/-(stiffness|damping)$/.test(n));
    if (!names.length) continue;
    out.push(`## ${g}`, '', '| Token | Value | Dark | Notes |', '|---|---|---|---|');
    for (const n of names) { const t = T[n]; out.push(`| \`${n}\` | ${short(t.value).replace(/\|/g, '\\|')} | ${t.modes && t.modes.dark ? short(t.modes.dark) : ''} | ${(t.description || '').replace(/\|/g, '\\|')} |`); }
    out.push('');
  }
  refs['tokens.md'] = out.join('\n');
}
{
  const I = JSON.parse(readFileSync(join(comp, 'icons/names.json'), 'utf8'));
  const rows = Object.entries(I.names).map(([n, src]) => `| \`${n}\` | ${src} |`);
  refs['icons.md'] = `# S4 Orion icon vocabulary\n\nGENERATED by scripts/build.mjs from components/icons/names.json. Use the name in \`<span class="s4-icon" data-icon="name"></span>\`; the second column is the ${I.set} icon it draws today.\nArrows and chevrons are Linear, everything else Bold Duotone. Unknown names log \`S4: unknown icon\` in the console. Another icon: \`S4.icon.add({ name: '<svg body>' })\`.\n\n| Name | ${I.set} icon |\n|---|---|\n${rows.join('\n')}\n`;
}
for (const f of ['color', 'typography', 'shape', 'spacing', 'elevation', 'motion', 'glass', 'accessibility']) {
  const src = join(root, 'docs/foundations', f + '.md');
  if (!existsSync(src)) { problems.push(`missing docs/foundations/${f}.md`); continue; }
  refs[f + '.md'] = `<!-- GENERATED copy of docs/foundations/${f}.md (scripts/build.mjs). Edit the original. -->\n` + readFileSync(src, 'utf8');
}
for (const [f, c] of Object.entries(refs)) outputs['skill/s4-orion/references/' + f] = c;

if (problems.length) { console.error(problems.map((p) => '  x ' + p).join('\n')); process.exit(1); }
if (CHECK) {
  const stale = Object.entries(outputs).filter(([f, c]) => !existsSync(join(root, f)) || readFileSync(join(root, f), 'utf8') !== c).map(([f]) => f)
    .concat(Object.entries(copies).filter(([to, from]) => !existsSync(join(root, to)) || !readFileSync(join(root, to)).equals(readFileSync(join(root, from)))).map(([f]) => f));
  if (stale.length) { console.error(`Stale bundle (run npm run build): ${stale.join(', ')}`); process.exit(1); }
  console.log(`Bundle up to date: ${imports.length} stylesheets, ${jsOrder.length} scripts.`);
} else {
  mkdirSync(skillAssets, { recursive: true }); mkdirSync(join(root, 'skill/s4-orion/references'), { recursive: true });
  for (const [f, c] of Object.entries(outputs)) writeFileSync(join(root, f), c);
  for (const [to, from] of Object.entries(copies)) copyFileSync(join(root, from), join(root, to));
  const kb = (s) => (Buffer.byteLength(s) / 1024).toFixed(0) + ' KB';
  console.log(`Built components/orion.css (${kb(cssRepo)}) and orion.js (${kb(js)}) from ${imports.length} stylesheets and ${jsOrder.length} scripts; copied assets to skill/s4-orion/assets/`);
}
